/**
 * Valida el formato de un correo y rechaza dominios desechables conocidos.
 */
export function validateEmail(email: string): { ok: boolean; error?: string } {
    const value = String(email || '').trim().toLowerCase();

    if (!value || !EMAIL_REGEX.test(value)) {
        return { ok: false, error: 'Ingresa un correo electrónico válido.' };
    }

    const domain = value.split('@')[1];
    if (DISPOSABLE_DOMAINS.has(domain)) {
        return { ok: false, error: 'No se permiten correos temporales o desechables.' };
    }

    return { ok: true };
}